"""Deterministic episodic target task using cached full-connectome features."""

from __future__ import annotations

import json
import math
import time
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np

from environment import AngularSensor, World2D

from .policy import LinearSoftmaxPolicy


@dataclass(frozen=True)
class RewardConfig:
    distance_progress: float = 1.0
    orientation_progress: float = 0.20
    step_cost: float = 0.01
    motion_cost: float = 0.02
    success_bonus: float = 3.0


@dataclass(frozen=True)
class TrainingConfig:
    max_steps: int = 24
    success_distance: float = 1.0
    learning_rate: float = 0.025
    gamma: float = 0.97
    baseline_retention: float = 0.95
    gradient_clip: float = 5.0


@dataclass(frozen=True)
class EpisodeResult:
    episode: int
    seed: int
    steps: int
    total_reward: float
    success: bool
    termination_reason: str
    elapsed_seconds: float
    initial_distance: float
    final_distance: float
    final_angle_error: float
    gradient_norm: float
    weight_delta_norm: float

    def serializable(self) -> dict[str, object]:
        return asdict(self)


class NeuralFeatureTable:
    """Fixed feature lookup generated by the full Phase 3.5 connectome."""

    def __init__(self, features: dict[str, np.ndarray], scale: float = 50.0) -> None:
        self.features = {key: np.asarray(value, dtype=np.float64) for key, value in features.items()}
        self.scale = scale

    @classmethod
    def from_phase35(cls, path: Path, scale: float = 50.0) -> "NeuralFeatureTable":
        payload = json.loads(path.read_text(encoding="utf-8"))
        features: dict[str, np.ndarray] = {}
        for outcome in payload["outcomes"]:
            response = outcome["response"]
            features[outcome["condition"]] = np.array(
                [
                    1.0,
                    response["left_activity"] / scale,
                    response["right_activity"] / scale,
                    response["total_activity"] / scale,
                ],
                dtype=np.float64,
            )
        expected = {"far_left", "left", "center", "right", "far_right", "not_visible"}
        if set(features) != expected:
            raise ValueError(f"incomplete neural feature table: {set(features)}")
        return cls(features, scale)

    def for_sector(self, sector: str | None) -> np.ndarray:
        return self.features[sector or "not_visible"].copy()


def wrap_angle(angle: float) -> float:
    return (angle + math.pi) % (2.0 * math.pi) - math.pi


def target_metrics(world: World2D) -> tuple[float, float]:
    dx = world.target_x - world.x
    dy = world.target_y - world.y
    return math.hypot(dx, dy), wrap_angle(math.atan2(dy, dx) - world.heading)


class TargetTask:
    def __init__(self, features: NeuralFeatureTable, reward: RewardConfig | None = None) -> None:
        self.features = features
        self.reward = reward or RewardConfig()
        self.sensor = AngularSensor(field_of_view=math.pi, max_distance=20.0)

    @staticmethod
    def make_world(rng: np.random.Generator) -> World2D:
        start_x, start_y, heading = 15.0, 5.0, math.pi / 2.0
        bearing = rng.uniform(math.radians(-70.0), math.radians(70.0))
        distance = rng.uniform(4.0, 8.0)
        target_heading = heading + bearing
        target = (start_x + distance * math.cos(target_heading), start_y + distance * math.sin(target_heading))
        world = World2D(width=30.0, height=30.0, start_x=start_x, start_y=start_y, start_heading=heading)
        world.reset(target)
        return world

    def step_reward(self, before: tuple[float, float, float], after: tuple[float, float, float], world: World2D) -> tuple[float, float, float]:
        before_x, before_y, before_heading = before
        after_x, after_y, after_heading = after
        before_distance = math.hypot(world.target_x - before_x, world.target_y - before_y)
        after_distance, after_angle = target_metrics(world)
        before_angle = wrap_angle(math.atan2(world.target_y - before_y, world.target_x - before_x) - before_heading)
        translation = math.hypot(after_x - before_x, after_y - before_y)
        rotation = abs(wrap_angle(after_heading - before_heading))
        reward = (
            self.reward.distance_progress * (before_distance - after_distance)
            + self.reward.orientation_progress * (abs(before_angle) - abs(after_angle))
            - self.reward.step_cost
            - self.reward.motion_cost * (translation + rotation)
        )
        return reward, after_distance, after_angle

    def run_episode(
        self,
        policy: LinearSoftmaxPolicy,
        rng: np.random.Generator,
        *,
        episode: int,
        seed: int,
        config: TrainingConfig,
        train: bool,
    ) -> EpisodeResult:
        started = time.perf_counter()
        world = self.make_world(rng)
        initial_distance, _ = target_metrics(world)
        trajectory: list[tuple[np.ndarray, int, np.ndarray, float]] = []
        total_reward = 0.0
        success = False
        final_distance = initial_distance
        final_angle = 0.0
        for step in range(1, config.max_steps + 1):
            observation = self.sensor.observe(world)
            features = self.features.for_sector(observation.sector)
            action_index, action, probabilities = policy.sample(features, rng)
            before = world.state
            after = world.step(action)
            reward, final_distance, final_angle = self.step_reward(before, after, world)
            success = final_distance <= config.success_distance
            if success:
                reward += self.reward.success_bonus
            trajectory.append((features, action_index, probabilities, reward))
            total_reward += reward
            if success:
                break
        update = {"gradient_norm": 0.0, "weight_delta_norm": 0.0}
        if train:
            update = policy.apply_reinforce(
                trajectory,
                learning_rate=config.learning_rate,
                gamma=config.gamma,
                baseline_retention=config.baseline_retention,
                gradient_clip=config.gradient_clip,
            )
        return EpisodeResult(
            episode=episode,
            seed=seed,
            steps=len(trajectory),
            total_reward=total_reward,
            success=success,
            termination_reason="success" if success else "max_steps",
            elapsed_seconds=time.perf_counter() - started,
            initial_distance=initial_distance,
            final_distance=final_distance,
            final_angle_error=final_angle,
            gradient_norm=float(update["gradient_norm"]),
            weight_delta_norm=float(update["weight_delta_norm"]),
        )
